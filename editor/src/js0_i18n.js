/** Translates a string (and fills {placeholders}). Unknown strings fall back to English. */
function _(s, vars) {
  let r = (LANG === 'es' && ES[s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return r;
}

/** Re-translates every static element of the page. */
function applyI18n() {
  document.querySelectorAll('[data-i]').forEach(el => {
    if (!el.dataset.k) el.dataset.k = el.textContent.trim();
    el.textContent = _(el.dataset.k);
  });
  document.querySelectorAll('[data-it]').forEach(el => {
    if (!el.dataset.kt) el.dataset.kt = el.getAttribute('title') || '';
    el.title = _(el.dataset.kt);
  });
  document.querySelectorAll('[data-ip]').forEach(el => {
    if (!el.dataset.kp) el.dataset.kp = el.getAttribute('placeholder') || '';
    el.placeholder = _(el.dataset.kp);
  });
}
